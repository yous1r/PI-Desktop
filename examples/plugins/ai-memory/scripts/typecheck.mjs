import ts from 'typescript';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tomlEntry } from './dependencies.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const configuration = ts.readConfigFile(resolve(root, 'tsconfig.json'), ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(configuration.config, ts.sys, root);
const toml = await tomlEntry();
parsed.options.paths = { 'smol-toml': [toml.declaration] };
const program = ts.createProgram(parsed.fileNames, parsed.options);
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length) console.error(ts.formatDiagnosticsWithColorAndContext(diagnostics, { getCanonicalFileName: value => value, getCurrentDirectory: () => root, getNewLine: () => '\n' }));
process.exitCode = diagnostics.length ? 1 : 0;
