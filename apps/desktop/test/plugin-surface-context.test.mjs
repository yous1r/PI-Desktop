import assert from "node:assert/strict";
import test from "node:test";
import { EventEmitter } from "node:events";
import { register } from "node:module";
register(new URL("./helpers/plugin-surface-electron-hook.mjs", import.meta.url));
const { PluginViewHost } = await import("../electron/main/plugin-view-host.ts");
const { pages } = await import("./helpers/plugin-surface-electron.mjs");
const context = (id, generation = 1) => ({ workspaceId:id, projectId:id, authority:{kind:"remote",hostKey:"host"}, roots:[{path:`/work/${id}`,name:id,primary:true}], platform:"linux", connectionState:"connected", generation });
const request = (id, sessionId = id, generation = 1) => ({pluginId:"test.plugin",viewId:"files",htmlPath:"C:/fixtures/view.html",locale:"en",theme:"light",context:context(id,generation),sessionId});
test("retained workspace views keep session ownership and late hide/close cannot affect another surface", async () => {
  const host = new PluginViewHost();
  const contents = Object.assign(new EventEmitter(), {isDestroyed:()=>false,getZoomFactor:()=>1});
  const children = [];
  host.setWindow({isDestroyed:()=>false,webContents:contents,contentView:{children,addChildView:view=>children.push(view),removeChildView:view=>children.splice(children.indexOf(view),1)}});
  const a = host.open(request("a")); const pageA = pages.at(-1);
  host.setVisible("test.plugin","files",true,a);
  assert.equal(children[0].webContents,pageA);
  assert.deepEqual(host.contextForSender(pageA.id),{context:context("a"),sessionId:"a"});
  const b = host.open(request("b")); const pageB = pages.at(-1);
  host.setVisible("test.plugin","files",true,b);
  host.setVisible("test.plugin","files",false,a);
  assert.equal(children[0].webContents,pageB);
  host.close("test.plugin","files");
  assert.equal(host.has("test.plugin","files",b),true);
  host.close("test.plugin","files",a);
  assert.equal(pageA.destroyed,true); assert.equal(host.contextForSender(pageA.id),undefined);
  assert.equal(children[0].webContents,pageB);
  assert.equal(host.open(request("b")),b);
  const otherSession = host.open(request("b","other"));
  assert.notEqual(otherSession,b);
  const rebound = host.open(request("b","b",2));
  assert.notEqual(rebound,b);
  host.broadcast("workspace:changed",{path:"wrong"});
  assert.equal(pageB.sent.length,0);
  host.broadcast("app:locale-changed",{locale:"en"});
  assert.equal(pageB.sent.length,1);
  host.close("different.plugin","files",b);
  assert.equal(pageB.destroyed,false);
  await host.dispose(); assert.equal(children.length,0);
  assert.equal(host.contextForSender(pageB.id),undefined);
});
test("legacy desktop views retain the public view key", async () => {
  const host = new PluginViewHost();
  const input = request("desktop"); delete input.context;
  const id = host.open(input);
  assert.equal(host.has("test.plugin","files"),true);
  assert.equal(host.open({...input,sessionId:"other"}),id);
  host.close("test.plugin","files");
  assert.equal(host.has("test.plugin","files"),false);
  await host.dispose();
});
